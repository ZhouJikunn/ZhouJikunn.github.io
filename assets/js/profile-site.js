async function loadSite(){
  const response=await fetch('/content/site.json',{cache:'no-store'});
  if(!response.ok) return;
  const data=await response.json(),p=data.profile;
  const one=selector=>document.querySelector(selector);
  document.querySelectorAll('[data-name]').forEach(el=>el.textContent=p.name);
  document.querySelectorAll('[data-initials]').forEach(el=>el.textContent=p.initials);
  document.querySelectorAll('[data-name-en]').forEach(el=>el.textContent=p.nameEn);
  document.querySelectorAll('[data-bio]').forEach(el=>el.textContent=p.bio);
  document.querySelectorAll('[data-role]').forEach(el=>el.textContent=p.role);
  document.querySelectorAll('[data-org]').forEach(el=>el.textContent=p.organization);
  document.querySelectorAll('[data-location]').forEach(el=>el.textContent=`⌖ ${p.location}`);
  document.querySelectorAll('[data-email-link]').forEach(el=>el.href=`mailto:${p.email}`);
  document.querySelectorAll('[data-email]').forEach(el=>el.textContent=p.email);
  document.querySelectorAll('[data-portrait]').forEach(el=>{if(p.image) el.src=p.image;el.alt=`${p.name}的个人照片`;});
  const interests=one('#interest-chips');
  if(interests) interests.innerHTML=p.interests.map(x=>`<span>${x}</span>`).join('');
  const research=one('#research-topics');
  if(research) research.innerHTML=data.research.map((x,i)=>`<div class="topic"><strong>${String(i+1).padStart(2,'0')}</strong><span>${x}</span></div>`).join('');
  const experience=one('#experience-list');
  if(experience) experience.innerHTML=(data.experience||[]).map((x,i)=>`<article><div class="timelineMarker"><span>${String(i+1).padStart(2,'0')}</span></div><p class="years">${x.years}</p><div><h3>${x.title}</h3><strong>${x.place}</strong><p>${x.note||''}</p></div></article>`).join('')||'<p class="emptyHint">教育与工作经历待补充。</p>';
  const publications=one('#publication-list');
  if(publications) publications.innerHTML=(data.publications||[]).map((x,i)=>`<article><div class="pubNo">${String(i+1).padStart(2,'0')}<span>${x.year}</span></div><div class="pubBody"><p class="pubType">${x.type||'PUBLICATION'}</p><h3>${x.title}</h3><p>${x.authors||''}</p><strong>${x.venue||''}</strong><div class="chips">${(x.tags||[]).map(t=>`<span>${t}</span>`).join('')}</div></div>${x.href?`<a href="${x.href}" aria-label="查看论文">↗</a>`:''}</article>`).join('');
  const publicationEmpty=one('#publication-empty');
  if(publicationEmpty) publicationEmpty.hidden=(data.publications||[]).length>0;
  const updates=one('#updates-list');
  if(updates) updates.innerHTML=(data.updates||[]).map((x,i)=>`<article class="${i===0?'featuredNote':''}"><div class="noteDate"><strong>${x.date}</strong><span>${x.year||''}</span></div><div><span class="noteKind">${x.kind||'动态'}</span><p>${x.text}</p><small>${x.meta||''}</small></div></article>`).join('');
  const updatesEmpty=one('#updates-empty');
  if(updatesEmpty) updatesEmpty.hidden=(data.updates||[]).length>0;
  document.querySelectorAll('[data-social-links]').forEach(el=>{el.innerHTML=p.links.map(x=>`<a href="${x.href}">${x.label} ↗</a>`).join('');});
}
loadSite().catch(()=>{});
